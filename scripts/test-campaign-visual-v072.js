assert.match(css, /\.swipe-stamp[^\n]*inset:50%/, 'Swipe labels are centered');
assert.match(css, /\.swipe-card\[data-swipe="ai"\]::before/, 'AI directional green trail');
assert.match(css, /\.swipe-card\[data-swipe="human"\]::before/, 'Human directional blue trail');
assert.match(js, /style\.setProperty\('--drag-blur'/, 'Blur strength grows with drag distance');
assert.match(css, /@keyframes v072-halo/, 'Strong green/red feedback has dedicated animation');
