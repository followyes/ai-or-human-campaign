import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (p) => readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const html = read('campaign.html');
const css = read('css/campaign.css');
const js = read('js/campaign-map.js');
assert.match(html, /class="map-status"[\s\S]*?id="map-sound-toggle"[\s\S]*?class="lives-panel"/, 'Map sound control is a sibling before the heart panel');
assert.match(html, /class="play-status"[\s\S]*?id="play-hearts"[\s\S]*?id="sound-toggle"/, 'Sound control is visible by play hearts');
assert.match(js, /for \(const toggle of soundToggles\)/, 'Sound controls stay synchronized');
assert.match(css, /\.swipe-stamp[^\n]*inset:50%/, 'Swipe labels are centered');
assert.match(css, /\.swipe-card\[data-swipe="ai"\]::before/, 'AI directional trail');
assert.match(css, /\.swipe-card\[data-swipe="human"\]::before/, 'Human directional trail');
assert.match(js, /style\.setProperty\('--drag-blur'/, 'Blur strength grows with drag distance');
assert.doesNotMatch(css, /repeating-linear-gradient/, 'No stripes or repeating lines in color blur');
assert.match(css, /\.swipe-area::before \{\s*inset:0;/, 'Glow remains inside its soft radial bounds');
assert.match(css, /--v073-clear:rgba\(/, 'Radial gradient fades to transparent in the same color');
assert.match(js, /card\.style\.transform = `translate3d\(\$\{Math\.max\(-140/, 'Swipe transforms are purely horizontal');
assert.doesNotMatch(js, /rotate\(\$\{\(dx/, 'Swipe never rotates the card');
assert.match(css, /@keyframes v072-halo/, 'Strong green/red feedback has dedicated animation');
assert.match(css, /@keyframes v072-card-rim/, 'Card itself has strong colored rim');
assert.match(js, /button\.className = `path-node \$\{done/, 'Visual state controls node class');
assert.match(js, /const revealLocked = unlockState\?\.nextUid/, 'Next stage is truly locked during reveal');
assert.match(js, /symbol\.textContent = nextStage\.isBoss \? '♛'/, 'Lock icon actually swaps to level icon');
assert.match(css, /@keyframes v072-lock-tremble/, 'Lock trembles');
assert.match(css, /@keyframes v072-unlock-number/, 'Level number reveal');
assert.match(css, /@media\(prefers-reduced-motion:reduce\)/, 'Reduced motion behavior');
assert.match(html, /campaign\.css\?v=0\.9\.0/, 'Fresh CSS cache version');
assert.match(html, /campaign-map\.js\?v=0\.9\.0/, 'Fresh JavaScript cache version');
console.log('PASS: v0.7.3 sound outside map hearts, smooth glow, straight horizontal swipe, no striped blur');
