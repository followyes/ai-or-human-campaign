import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const js = readFileSync(new URL('../js/campaign-map.js', import.meta.url), 'utf8');
const html = readFileSync(new URL('../campaign.html', import.meta.url), 'utf8');
const css = readFileSync(new URL('../css/campaign.css', import.meta.url), 'utf8');
const winBlock = js.slice(js.indexOf('function winRun() {'), js.indexOf('\nfunction loseRun('));
assert.match(winBlock, /showUnlockOnMap\(stage, nextStage, wasCompleted\)/, 'completed stage must return to the map with an unlock reveal');
assert.doesNotMatch(winBlock, /showResult\(/, 'success must not display a separate result screen');
assert.match(js, /markStableComplete\(progress, stage\.uid\)/, 'persist completed UUIDs');
assert.match(js, /requestAnimationFrame\(\(\) => scrollMapToStage/, 'focus completed/unlocked stage');
assert.match(js, /activeStages\.forEach\(\(stage, index\)/, 'map must render every stage, not a page of six');
assert.doesNotMatch(js, /worldPage|STAGES_PER_WORLD|#world-next|#world-prev/, 'no pagination');
assert.match(js, /pointerType !== 'mouse'/, 'desktop pointer dragging');
assert.match(js, /mapScroller\.scrollTop = mapDrag\.startScroll - diff/, 'drag adjusts map scrollTop');
assert.match(js, /suppressMapClick/, 'drag never clicks a stage accidentally');
assert.match(html, /id="map-scroll"[^>]*tabindex="0"/, 'keyboard-operable scroll region');
assert.match(html, /id="map-unlock-banner"[^>]*aria-live="polite"/, 'accessible unlock status');
assert.doesNotMatch(html, /id="world-prev"|id="world-next"/, 'no world page buttons');
assert.match(css, /overflow-y: auto/, 'native overflow for touch and wheel');
assert.match(css, /touch-action: pan-y/, 'native touch scrolling');
assert.match(css, /prefers-reduced-motion:reduce/, 'reduced-motion support');
console.log('PASS: scrollable continuous map, desktop drag, unlock return animation, stable IDs');
